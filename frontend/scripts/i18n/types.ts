import fs from "node:fs";
import { generatedFile, isTestFile, maskSource, type Messages, readLocale, rel, sourceFiles, translationFiles } from "./shared.ts";

const OPTIONAL_PLACEHOLDERS = new Set(["suffix", "prefix"]);
const NAMED_PLACEHOLDER = /\{([A-Za-z_]\w*)\}/g;
/** vue-i18n literal interpolation, like {'|'} to print a pipe or @ */
const LITERAL_INTERPOLATION = /\{'[^']*'\}/g;
const REGENERATE = "Run: npm run i18n:types";

/** Named placeholders of a message in order */
function placeholders(message: string): string[] {
  const names: string[] = [];
  for (const match of message.matchAll(NAMED_PLACEHOLDER)) {
    const name = match[1] ?? "";
    if (!names.includes(name)) names.push(name);
  }
  return names;
}

/** Returns a description of unsupported vue-i18n syntax, or null. */
function unsupportedSyntax(message: string): string | null {
  const rest = message.replace(LITERAL_INTERPOLATION, "").replace(NAMED_PLACEHOLDER, "");
  if (/[{}]/.test(rest)) return "braces other than {name} placeholders";
  if (rest.includes("|")) return "plural separator '|'";
  if (/@[.:]/.test(rest)) return "linked message '@:' / '@.'";
  return null;
}

function generate() {
  const messages = readLocale("en.json");
  const problems: string[] = [];
  const lines: string[] = [];
  for (const [key, message] of Object.entries(messages)) {
    const unsupported = unsupportedSyntax(message);
    if (unsupported) problems.push(`en.json: ${key} uses ${unsupported}, which the types do not support`);
    const names = placeholders(message);
    const params = names.length ? names.map((name) => JSON.stringify(name)).join(" | ") : "never";
    lines.push(`  ${JSON.stringify(key)}: ${params};`);
  }
  const content = `// This file is generated by scripts/i18n from src/i18n/locales/en.json.
// Run \`make generate-translation-types\` \`npm run i18n:types\` after changing en.json. Do not edit manually.

/** Every message in en.json mapped to the named placeholders. Used to type-check \`t()\` calls */
export interface MessageParams {
${lines.join("\n")}
}

/** Placeholders that callers may omit */
export type OptionalParam = ${[...OPTIONAL_PLACEHOLDERS].map((name) => JSON.stringify(name)).join(" | ")};
`;
  return { content, messages, problems };
}

/** Regenerates messages.generated.ts; returns the exit code. */
export function writeTypes(): number {
  const { content, messages, problems } = generate();
  if (problems.length) {
    for (const problem of problems) console.error(`✗ ${problem}`);
    return 1;
  }
  fs.writeFileSync(generatedFile, content);
  console.log(`Wrote ${rel(generatedFile)} (${Object.keys(messages).length} messages).`);
  return 0;
}

function checkGeneratedFile(expected: string): string[] {
  if (!fs.existsSync(generatedFile)) return [`${rel(generatedFile)} is missing. ${REGENERATE}`];
  if (fs.readFileSync(generatedFile, "utf8") !== expected) return [`${rel(generatedFile)} is out of date. ${REGENERATE}`];
  return [];
}

function checkLocalePlaceholders(enMessages: Messages): string[] {
  const problems: string[] = [];
  for (const file of translationFiles()) {
    for (const [key, message] of Object.entries(readLocale(file))) {
      const english = enMessages[key];
      if (english === undefined) continue;
      const expected = new Set(placeholders(english));
      const actual = new Set(placeholders(message));
      for (const name of actual) {
        if (!expected.has(name)) problems.push(`${file}: ${key} uses {${name}}, which en.json does not provide`);
      }
      for (const name of expected) {
        if (!actual.has(name) && !OPTIONAL_PLACEHOLDERS.has(name)) problems.push(`${file}: ${key} is missing {${name}}`);
      }
      const unsupported = unsupportedSyntax(message);
      if (unsupported) problems.push(`${file}: ${key} uses ${unsupported}`);
    }
  }
  return problems;
}

/** .ts files and .vue files with <script lang="ts"> are checked by vue-tsc */
function isTypeScript(file: string, text: string): boolean {
  if (file.endsWith(".ts")) return true;
  return file.endsWith(".vue") && /<script[^>]*lang=["']ts["']/.test(text);
}

const BYPASS_RULES = [
  {
    pattern: /from\s+["']vue-i18n["']/,
    message: "import useI18n from '@/i18n/index.ts' instead of 'vue-i18n'",
    inStrings: true,
  },
  {
    pattern: /(^|[^\w$])\$t\b/,
    message: "use t(...) from useI18n() in '@/i18n/index.ts' instead of $t(...), so the key and params are type-checked",
    inStrings: false,
  },
];

// The start of a t(...) call: t(, $t(, this.$t( or i18n.global.t(
const CALL_START = /(?:(?<![\w$.])(?:\$t|t|i18n\.global\.t)|\bthis\.\$t)\(/g;

interface Params {
  names: Set<string>;
  dynamic: boolean;
}

const lineOf = (text: string, index: number) => text.slice(0, index).split("\n").length;

function skipSpaces(text: string, index: number): number {
  let i = index;
  while (i < text.length && /\s/.test(text.charAt(i))) i++;
  return i;
}

/** Reads a string literal starting at `index`; returns null for anything else or a dynamic template */
function readStringLiteral(text: string, index: number): { value: string; end: number } | null {
  const quote = text.charAt(index);
  if (quote !== '"' && quote !== "'" && quote !== "`") return null;
  let i = index + 1;
  let value = "";
  while (i < text.length && text.charAt(i) !== quote) {
    if (text.charAt(i) === "\\") {
      value += text.charAt(i + 1);
      i += 2;
      continue;
    }
    if (quote === "`" && text.charAt(i) === "$" && text.charAt(i + 1) === "{") return null;
    value += text.charAt(i);
    i++;
  }
  return i < text.length ? { value, end: i + 1 } : null;
}

const isQuote = (ch: string) => ch === '"' || ch === "'" || ch === "`";

function skipString(text: string, index: number): number {
  const quote = text.charAt(index);
  let i = index + 1;
  while (i < text.length) {
    const ch = text.charAt(i);
    if (ch === "\\") i++;
    else if (ch === quote) return i + 1;
    i++;
  }
  return -1;
}

const CLOSERS: Record<string, string> = { "{": "}", "[": "]", "(": ")" };

/** Finds the index of the bracket closing the one at `index`, skipping strings. */
function findClosing(text: string, index: number): number {
  const stack = [CLOSERS[text.charAt(index)]];
  let i = index + 1;
  while (i < text.length && stack.length) {
    const ch = text.charAt(i);
    if (isQuote(ch)) {
      const end = skipString(text, i);
      if (end === -1) return -1;
      i = end;
      continue;
    }
    const closer = CLOSERS[ch];
    if (closer) stack.push(closer);
    else if (ch === stack.at(-1)) stack.pop();
    i++;
  }
  return stack.length ? -1 : i - 1;
}

/** Property names of the object literal at `index`; `dynamic` when a spread or computed key hides some */
function readObjectKeys(text: string, index: number): Params | null {
  const close = findClosing(text, index);
  if (close === -1) return null;
  const names = new Set<string>();
  let dynamic = false;
  let segmentStart = index + 1;
  let i = index + 1;
  const flush = (end: number) => {
    const segment = text.slice(segmentStart, end).trim();
    if (!segment) return;
    if (segment.startsWith("...") || segment.startsWith("[")) {
      dynamic = true;
      return;
    }
    const match = segment.match(/^(?:([A-Za-z_$][\w$]*)|'([^']*)'|"([^"]*)")\s*(?::|$)/);
    const name = match?.[1] ?? match?.[2] ?? match?.[3];
    if (name === undefined) dynamic = true;
    else names.add(name);
  };
  while (i < close) {
    const ch = text.charAt(i);
    if (isQuote(ch)) {
      i = skipString(text, i);
      continue;
    }
    if (ch === "{" || ch === "[" || ch === "(") {
      i = findClosing(text, i) + 1;
      continue;
    }
    if (ch === ",") {
      flush(i);
      segmentStart = i + 1;
    }
    i++;
  }
  flush(close);
  return { names, dynamic };
}

/**
 * Yields every t(...) call whose first argument is a literal key. `text` is the source without
 * comments, `bare` the same without the content of its strings
 */
export function* literalCalls(text: string, bare: string): Generator<{ key: string; params: Params; index: number }> {
  for (const match of bare.matchAll(CALL_START)) {
    const keyStart = skipSpaces(text, match.index + match[0].length);
    const key = readStringLiteral(text, keyStart);
    if (!key) continue; // only vue-tsc can check it
    let i = skipSpaces(text, key.end);
    if (text.charAt(i) !== "," && text.charAt(i) !== ")") continue; // 'prefix.' + name if the key isn't literal
    let params: Params = { names: new Set(), dynamic: false };
    if (text.charAt(i) === ",") {
      i = skipSpaces(text, i + 1);
      if (text.charAt(i) === "{") params = readObjectKeys(text, i) ?? params;
      else if (text.charAt(i) !== ")") params = { names: new Set(), dynamic: true };
    }
    yield { key: key.value, params, index: match.index };
  }
}

function checkCall(key: string, params: Params, messages: Messages): string[] {
  const expected = messages[key];
  if (expected === undefined) return [`unknown translation key "${key}"`];
  if (params.dynamic) return []; // spread or variable: names unknown
  const known = new Set(placeholders(expected));
  const problems: string[] = [];
  for (const name of params.names) {
    if (!known.has(name)) problems.push(`"${key}" does not take a {${name}} param`);
  }
  for (const name of known) {
    if (!params.names.has(name) && !OPTIONAL_PLACEHOLDERS.has(name)) problems.push(`"${key}" is missing its {${name}} param`);
  }
  return problems;
}

function checkTypedUsage(messages: Messages, strict: boolean): string[] {
  const problems: string[] = [];
  for (const file of sourceFiles(true)) {
    if (isTestFile(file)) continue; // tests t/$t with throwaway keys
    const text = fs.readFileSync(file, "utf8");
    const code = maskSource(file, text);
    const bare = maskSource(file, text, true);
    if (strict || isTypeScript(file, text)) {
      const codeLines = code.split("\n");
      const bareLines = bare.split("\n");
      for (const rule of BYPASS_RULES) {
        const lines = rule.inStrings ? codeLines : bareLines;
        for (const [index, line] of lines.entries()) {
          if (rule.pattern.test(line)) problems.push(`${rel(file)}:${index + 1}: ${rule.message}`);
        }
      }
    }
    for (const call of literalCalls(code, bare)) {
      for (const problem of checkCall(call.key, call.params, messages)) {
        problems.push(`${rel(file)}:${lineOf(text, call.index)}: ${problem}`);
      }
    }
  }
  return problems;
}

/** Checks the generated types, the placeholders of every locale and the t() calls in src/. With `strict`, raw `$t` and 'vue-i18n' */
export function checkTypes(strict: boolean): string[] {
  const { content, messages, problems } = generate();
  return [...problems, ...checkGeneratedFile(content), ...checkLocalePlaceholders(messages), ...checkTypedUsage(messages, strict)];
}
